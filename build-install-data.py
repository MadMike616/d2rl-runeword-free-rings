"""Generate the mod-independent installer payload compiled into the DLL."""

from itertools import combinations
import json
from pathlib import Path
import sys

from stage_tables import (
    DATA_FORMAT, KEY, LOCALES, PAIRS, PAIR_STATS, RING_LEVEL, RING_NAMES, RING_ROLLS,
    SET, SET_NAMES, TABLE_KEYS, add_oath_rows,
)


def quoted(value):
    return json.dumps(value, ensure_ascii=False)


class TableSeed:
    def __init__(self):
        self.rows = []

    def add(self, **fields):
        self.rows.append(fields)

    def tsv(self):
        header = list(dict.fromkeys(column for row in self.rows for column in row))
        lines = ["\t".join(header)]
        lines.extend("\t".join(str(row.get(column, "")) for column in header)
                     for row in self.rows)
        return "\n".join(lines)


def strings(name, entries):
    lines = [f"inline constexpr std::array {name}{{"]
    for key, translations in entries:
        fields = {"Key": key, **dict(zip(LOCALES, translations, strict=True))}
        line = json.dumps(fields, ensure_ascii=False, separators=(",", ":"))
        lines.append(f"    StringSeed{{{quoted(key)}, {quoted(line)}}},")
    return "\n".join(lines + ["};"])


def main(output):
    labels_path = Path(__file__).parent / "src/assets/bonus-labels.json"
    labels = json.loads(labels_path.read_text(encoding="utf-8"))
    tables = {name: TableSeed() for name in TABLE_KEYS}
    ids = {"setitems": "*ID", "skills": "*Id", "states": "*ID"}
    add_oath_rows(tables, {ring: f"@ring{i}" for i, ring in enumerate(RING_NAMES)}, "@skill", "@state")

    pairs = list(combinations(RING_NAMES, 2))
    if set(pairs) != set(PAIRS):
        raise ValueError("Missing or unexpected pair")
    stat_names = sorted(name for names, _ in PAIR_STATS.values() for name in names)
    properties = sorted({"aura"} | {name for rolls in RING_ROLLS.values() for name, _, _ in rolls})
    pair_lines, skill_strings = [], [(KEY, SET_NAMES), (KEY + "Effect", SET_NAMES)]
    for first, second in pairs:
        text = [[f"{a} + {b}"] for a, b in zip(RING_NAMES[first], RING_NAMES[second], strict=True)]
        values = {}
        for prop, amount in PAIRS[first, second].items():
            for locale, lines in zip(LOCALES, text, strict=True):
                label = labels[prop][locale]
                lines.append(label if prop == "cannot_freeze" else label % amount)
            values.update((name, amount) for name in PAIR_STATS[prop][0])
        pair_lines.append("    {" + ", ".join(str(values.get(name, 0)) for name in stat_names) + "},")
        skill_strings.append((KEY + "Pair" + first + second, tuple("\n".join(lines) for lines in text)))

    output.write_text("\n".join([
        "// Generated by build-install-data.py.",
        "#pragma once",
        "#include <array>",
        "#include <string_view>",
        "namespace InstallData {",
        "struct TableSeed { const wchar_t* filename; std::string_view keyColumn, idColumn, tsv; };",
        "struct StringSeed { std::string_view key, json; };",
        f"inline constexpr unsigned Format = {DATA_FORMAT}, RingLevel = {RING_LEVEL};",
        f"inline constexpr std::array Locales{{{', '.join(map(quoted, LOCALES))}}};",
        f"inline constexpr std::array StatNames{{{', '.join(map(quoted, stat_names))}}};",
        f"inline constexpr std::array RequiredProperties{{{', '.join(map(quoted, properties))}}};",
        "inline constexpr std::array Tables{",
        *(f'    TableSeed{{L"{name}.txt", {quoted(TABLE_KEYS[name])}, {quoted(ids.get(name, ""))}, {quoted(seed.tsv())}}},'
          for name, seed in tables.items()),
        "};",
        f"inline constexpr unsigned PairValues[{len(pairs)}][{len(stat_names)}]{{",
        *pair_lines,
        "};",
        strings("ItemNames", [(SET, SET_NAMES), *((names[0], names) for names in RING_NAMES.values())]),
        strings("Skills", skill_strings),
        "}",
        "",
    ]), encoding="utf-8")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
